% Plot the measured FULL STATIC transfer curve for resizing seed 44 at TT.

scriptPath = mfilename("fullpath");
scriptDir = fileparts(scriptPath);
caseDir = fileparts(scriptDir);
inputPath = fullfile(caseDir, "csv", ...
    "current_s116_transitions_up.csv");
outputDir = fullfile(caseDir, "plots");
pngPath = fullfile(outputDir, ...
    "seed44_tt_full_static_transfer_curve.png");
pdfPath = fullfile(outputDir, ...
    "seed44_tt_full_static_transfer_curve.pdf");
curveCsvPath = fullfile(caseDir, "csv", ...
    "seed44_tt_full_static_transfer_curve.csv");

assert(isfile(inputPath), "Transition file not found: %s", inputPath);
if ~isfolder(outputDir)
    mkdir(outputDir);
end

transitions = readtable(inputPath, TextType="string");
requiredVariables = ["mismatch_seed", "target_transition", ...
    "transition_v", "status"];
assert(all(ismember(requiredVariables, ...
    string(transitions.Properties.VariableNames))), ...
    "Transition CSV is missing one or more required variables.");

transitions = sortrows(transitions, "target_transition");
target = transitions.target_transition;
thresholdV = transitions.transition_v;

assert(height(transitions) == 255, ...
    "Expected 255 transitions, found %d.", height(transitions));
assert(isequal(target(:), (1:255).'), ...
    "Transition targets are not exactly 1 through 255.");
assert(all(transitions.mismatch_seed == 44), ...
    "Input data does not exclusively contain mismatch seed 44.");
assert(all(transitions.status == "PASS"), ...
    "At least one transition does not have PASS status.");
assert(all(isfinite(thresholdV)), ...
    "At least one transition voltage is not finite.");
assert(all(diff(thresholdV) > 0), ...
    "Transition voltages are not strictly increasing.");

qEndpointV = (thresholdV(end) - thresholdV(1)) / 254;
inputMinV = thresholdV(1) - qEndpointV / 2;
inputMaxV = thresholdV(end) + qEndpointV / 2;

curveInputV = [inputMinV; thresholdV; inputMaxV];
outputCode = [0; (1:255).'; 255];
pointRole = ["extrapolated_low"; ...
    repmat("measured_transition", 255, 1); ...
    "extrapolated_high"];
curve = table(curveInputV, outputCode, pointRole, ...
    VariableNames=["input_diff_v", "output_code", "point_role"]);
writetable(curve, curveCsvPath);

idealInputV = linspace(inputMinV, inputMaxV, 1200).';
idealCode = 0.5 + (idealInputV - thresholdV(1)) / qEndpointV;
idealCode = min(max(idealCode, 0), 255);

figureHandle = figure(Visible="off", Color="white", ...
    Position=[100 100 1600 950]);
axesHandle = axes(figureHandle);
set(axesHandle, Color="white", XColor=[0.12 0.12 0.12], ...
    YColor=[0.12 0.12 0.12], GridColor=[0.72 0.72 0.72], ...
    GridAlpha=0.55);
hold(axesHandle, "on");
stairs(axesHandle, curveInputV, outputCode, ...
    LineWidth=1.8, Color=[0.00 0.35 0.72], ...
    DisplayName="Measured output code");
plot(axesHandle, idealInputV, idealCode, "--", ...
    LineWidth=1.4, Color=[0.85 0.24 0.14], ...
    DisplayName="Endpoint-fit ideal line");
scatter(axesHandle, thresholdV([1 end]), [0.5 254.5], ...
    44, [0.15 0.15 0.15], "filled", ...
    DisplayName="T1 / T255");

grid(axesHandle, "on");
box(axesHandle, "on");
xlim(axesHandle, [inputMinV inputMaxV]);
ylim(axesHandle, [-4 259]);
xlabel(axesHandle, "Differential input, V_{INP}-V_{INN} (V)");
ylabel(axesHandle, "ADC output code (decimal)");
titleHandle = title(axesHandle, { ...
    "FULL STATIC Transfer Curve - Seed 44, TT"; ...
    "XM5/XM6 W=8.2524 \mum; XM7/XM11 W=16.8587 \mum"});
set(titleHandle, Color=[0.12 0.12 0.12]);
legendHandle = legend(axesHandle, Location="northwest");
set(legendHandle, Color="white", TextColor=[0.12 0.12 0.12], ...
    EdgeColor=[0.45 0.45 0.45]);
set(axesHandle, FontName="Arial", FontSize=13, LineWidth=1.0);

annotation(figureHandle, "textbox", [0.57 0.16 0.31 0.12], ...
    String=sprintf("255/255 transitions PASS\n" + ...
    "T1 = %.6f V\nT255 = %.6f V\n" + ...
    "Endpoint-fit Q = %.3f mV", ...
    thresholdV(1), thresholdV(end), qEndpointV * 1e3), ...
    FitBoxToText="on", BackgroundColor="white", ...
    EdgeColor=[0.55 0.55 0.55], Color=[0.12 0.12 0.12], ...
    FontName="Arial", FontSize=11);

exportgraphics(figureHandle, pngPath, Resolution=220);
exportgraphics(figureHandle, pdfPath, ContentType="vector");
close(figureHandle);

fprintf("Transfer curve generated successfully.\n");
fprintf("Input: %s\n", inputPath);
fprintf("PNG: %s\n", pngPath);
fprintf("PDF: %s\n", pdfPath);
fprintf("Curve CSV: %s\n", curveCsvPath);
fprintf("Transitions: %d; T1 = %.9f V; T255 = %.9f V; Qep = %.9f V\n", ...
    height(transitions), thresholdV(1), thresholdV(end), qEndpointV);
